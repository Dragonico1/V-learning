/**
 * Textos de la interfaz según el perfil de accesibilidad.
 * Con el perfil cognitivo activo se usa la versión sencilla: frases cortas,
 * palabras conocidas y sin tecnicismos.
 *
 *   const t = useTexto();
 *   <h2>{t("Evaluaciones pendientes", "Pruebas por hacer")}</h2>
 *   <span>{t("Módulo")}</span> // el diccionario devuelve "Parte"
 *
 * Si no se da versión sencilla, se busca en el diccionario de términos y frases.
 */
export function useTexto() {
  const { categorias } = usePrefs();
  const sencillo = categorias.includes("COGNITIVA");
  return (normal, versionSencilla) => {
    if (!sencillo) return normal;
    if (versionSencilla != null) return versionSencilla;
    return FRASES[normal] ?? TERMINOS[normal] ?? normal;
  };
}
