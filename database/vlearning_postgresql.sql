-- ================================================================
-- Actualiza fecha_actualizacion cuando se modifica la fila (equivale a los triggers de T-SQL).
-- ================================================================
CREATE FUNCTION fn_actualizar_fecha_actualizacion() RETURNS trigger AS $$
BEGIN
    NEW.fecha_actualizacion := LOCALTIMESTAMP(0);
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_cursos_fecha_actualizacion_update
    BEFORE UPDATE ON cursos
    FOR EACH ROW EXECUTE FUNCTION fn_actualizar_fecha_actualizacion();

CREATE TRIGGER trg_perfiles_accesibilidad_fecha_actualizacion_update
    BEFORE UPDATE ON perfiles_accesibilidad
    FOR EACH ROW EXECUTE FUNCTION fn_actualizar_fecha_actualizacion();

CREATE TRIGGER trg_reglas_gamificacion_fecha_actualizacion_update
    BEFORE UPDATE ON reglas_gamificacion
    FOR EACH ROW EXECUTE FUNCTION fn_actualizar_fecha_actualizacion();

