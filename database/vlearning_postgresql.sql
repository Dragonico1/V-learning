-- ================================================================
CREATE TABLE usuarios (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(150) NOT NULL,
    correo_institucional VARCHAR(180) NOT NULL,
    password_hash VARCHAR(128) NOT NULL,
    rol VARCHAR(15) NOT NULL,
    estado VARCHAR(25) NOT NULL DEFAULT 'PENDIENTE_PRIMER_ACCESO',
    fecha_creacion TIMESTAMP(0) NOT NULL DEFAULT LOCALTIMESTAMP(0),
    ultimo_acceso TIMESTAMP(0) NULL,
    intentos_fallidos INT NOT NULL DEFAULT 0,
    -- [EXT] HU-002 / CU-002: bloqueo temporal de 15 min tras 5 intentos fallidos.
    bloqueado_hasta TIMESTAMP(0) NULL,
    -- [EXT] HU-013 / CU-011: el usuario puede deshabilitar notificaciones.
    notificaciones_habilitadas BOOLEAN NOT NULL DEFAULT TRUE,
    -- [EXT] HU-013 / CU-011: canal preferido (plataforma, correo).
    canal_preferido VARCHAR(15) NOT NULL DEFAULT 'PLATAFORMA',
    -- [EXT] Segundo factor (OTP): obligatorio para INSTRUCTOR y ADMINISTRADOR (la aplicación lo
    --       fuerza por rol); el ESTUDIANTE puede desactivarlo desde Configuración.
    doble_factor_habilitado BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT uq_usuarios_correo UNIQUE (correo_institucional),
    CONSTRAINT ck_usuarios_intentos CHECK (intentos_fallidos >= 0),
    CONSTRAINT ck_usuarios_rol CHECK (rol IN ('ESTUDIANTE', 'INSTRUCTOR', 'ADMINISTRADOR')),
    CONSTRAINT ck_usuarios_estado CHECK (estado IN ('PENDIENTE_PRIMER_ACCESO', 'ACTIVO', 'BLOQUEADO', 'INACTIVO')),
    CONSTRAINT ck_usuarios_canal_preferido CHECK (canal_preferido IN ('PLATAFORMA', 'CORREO')) -- [EXT]
);
-- [EXT] SQL Server comparaba sin distinguir mayúsculas; PostgreSQL sí. Este índice evita correos
-- duplicados que solo difieren en mayúsculas (la aplicación además los guarda en minúsculas).
CREATE UNIQUE INDEX uq_usuarios_correo_minusculas ON usuarios (lower(correo_institucional));

