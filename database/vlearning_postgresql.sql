-- ================================================================
-- V-Learning - Esquema relacional para PostgreSQL (14 o superior)
-- Migrado desde SQL Server (T-SQL). Equivale al esquema fusionado anterior,
-- incluidas las tareas calificables, la moderación de mensajes, la fecha límite
-- de evaluaciones y el destino (enlace) de las notificaciones.
--
-- Ejecutar conectado a la base vlearning (ver 00_crear_bd.sql):
--   psql -U vlearning_admin -d vlearning -f database/postgresql/01_schema.sql
--
-- ADVERTENCIA: el script BORRA y vuelve a crear todas las tablas de V-Learning.
--
-- Criterios de tipos (valores conservadores):
--   * IDs INT con IDENTITY; SMALLINT para contadores pequeños (orden, nivel, fuente...).
--   * Fechas TIMESTAMP(0) (segundos); la aplicación asigna casi todas desde Java.
--   * VARCHAR(n) ajustado al máximo que la aplicación valida o al más largo de cada enumeración.
--   * TEXT solo donde la aplicación NO limita el largo (descripciones, cuerpos, enunciados).
--   * Puntajes DECIMAL(8,2) (hasta 999999,99) y porcentajes DECIMAL(5,2).
--
-- Convención: todo lo marcado [EXT] es una ampliación sobre el esquema oficial.
-- ================================================================

