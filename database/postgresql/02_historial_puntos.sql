-- ================================================================
-- V-Learning - Migración: historial de puntos (gráfica de actividad de 7 días)
-- Para bases YA creadas con una versión anterior de 01_schema.sql. Es idempotente.
--   psql -U vlearning_admin -d vlearning -f database/postgresql/02_historial_puntos.sql
-- (Las instalaciones nuevas ya la incluyen en 01_schema.sql.)
-- ================================================================
CREATE TABLE IF NOT EXISTS historial_puntos (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    estudiante_id INT NOT NULL,
    puntos INT NOT NULL,
    motivo VARCHAR(300),
    fecha TIMESTAMP(0) NOT NULL DEFAULT LOCALTIMESTAMP(0),
    CONSTRAINT ck_historial_puntos_puntos CHECK (puntos > 0),
    CONSTRAINT fk_historial_puntos_estudiante FOREIGN KEY (estudiante_id)
        REFERENCES estudiantes(id) ON UPDATE NO ACTION ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS idx_historial_puntos_estudiante_fecha ON historial_puntos (estudiante_id, fecha);
